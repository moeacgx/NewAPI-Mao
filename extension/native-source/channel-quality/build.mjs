import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// channel-quality 原生样式构建入口：把 Tailwind 生成产物（*.tailwind.css）限定在 .channel-quality-native 根节点内。
// 原生样式会作为文档级 <link> 注入宿主页面，未限定作用域时 .w-full/.flex/.block 等同名工具类会覆盖全局顶栏。
// 用法：node extension/native-source/channel-quality/build.mjs [输出目录]
const scope = ".channel-quality-native";
const directory = path.dirname(fileURLToPath(import.meta.url));
const outputDirectory = path.resolve(
  process.argv[2] ||
    path.join(directory, "../../builtin/channel-quality/public/native"),
);

function parse(css) {
  const nodes = [];
  let index = 0;
  while (index < css.length) {
    const open = css.indexOf("{", index);
    const semicolon = css.indexOf(";", index);
    if (open < 0) break;
    if (semicolon >= 0 && semicolon < open) {
      nodes.push({ prelude: css.slice(index, semicolon).trim() });
      index = semicolon + 1;
      continue;
    }
    let depth = 1;
    let end = open + 1;
    for (; depth > 0 && end < css.length; end++) {
      if (css[end] === "{") depth++;
      if (css[end] === "}") depth--;
    }
    nodes.push({
      prelude: css.slice(index, open).trim(),
      body: css.slice(open + 1, end - 1),
    });
    index = end;
  }
  return nodes;
}

function splitSelectors(prelude) {
  const list = [];
  let depth = 0;
  let current = "";
  for (let i = 0; i < prelude.length; i++) {
    const char = prelude[i];
    if (char === "\\") {
      current += char + (prelude[++i] ?? "");
      continue;
    }
    if (char === "(" || char === "[") depth++;
    if (char === ")" || char === "]") depth--;
    if (char === "," && depth === 0) {
      list.push(current.trim());
      current = "";
      continue;
    }
    current += char;
  }
  list.push(current.trim());
  return list;
}

function scopeNodes(nodes, defaults, lines) {
  for (const { prelude, body } of nodes) {
    if (body === undefined || prelude === "@layer properties") continue;
    if (prelude === "@layer utilities") {
      scopeNodes(parse(body), defaults, lines);
      continue;
    }
    if (prelude === "@layer theme") {
      for (const rule of parse(body))
        lines.push(
          `:where(${scope}) {${rule.body.replace(": spin ", ": channel-quality-spin ")}}`,
        );
      continue;
    }
    if (prelude.startsWith("@property")) {
      const initial = body.match(/initial-value:\s*([^;]+);/);
      if (initial)
        defaults.push(
          `  ${prelude.slice("@property".length).trim()}: ${initial[1].trim()};`,
        );
      continue;
    }
    if (prelude.startsWith("@keyframes")) {
      lines.push(
        `@keyframes channel-quality-${prelude.slice("@keyframes".length).trim()} {${body}}`,
      );
      continue;
    }
    if (prelude.startsWith("@media") || prelude.startsWith("@supports")) {
      const inner = [];
      scopeNodes(parse(body), defaults, inner);
      lines.push(`${prelude} {\n${inner.join("\n")}\n}`);
      continue;
    }
    lines.push(
      `${splitSelectors(prelude)
        .map((selector) => `:where(${scope}) ${selector}`)
        .join(", ")} {${body}}`,
    );
  }
}

function scopeStylesheet(source) {
  const defaults = [];
  const lines = [];
  scopeNodes(parse(source.replace(/\/\*[\s\S]*?\*\//g, "")), defaults, lines);
  const head = [`${scope} {\n  min-width: 0;\n}`];
  if (defaults.length)
    head.push(
      `@layer properties {\n:where(${scope}), :where(${scope}) *, :where(${scope}) ::before, :where(${scope}) ::after {\n${defaults.join("\n")}\n}\n}`,
    );
  return `/* Generated by extension/native-source/channel-quality/build.mjs. Do not edit. */\n${head.concat(["@layer utilities {"], lines, ["}"]).join("\n")}\n`;
}

await fs.mkdir(outputDirectory, { recursive: true });
for (const target of ["default", "classic"]) {
  const source = await fs.readFile(
    path.join(directory, `${target}.tailwind.css`),
    "utf8",
  );
  await fs.writeFile(
    path.join(outputDirectory, `${target}.css`),
    scopeStylesheet(source),
    "utf8",
  );
}
